export function getExercisesByIds(ids: string[]): ExerciseRecommendation[] {
  return ids
    .map((id) => EXERCISES.find((e) => e.id === id))
    .filter((e): e is ExerciseRecommendation => Boolean(e));
}

export function getExercisesForRegion(region: BodyRegion): ExerciseRecommendation[] {
  return EXERCISES.filter((e) => e.regions.includes(region));
}
